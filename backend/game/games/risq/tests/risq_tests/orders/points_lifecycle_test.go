func orderQueues(g *harness.Game, p int, unit uint64) [][]gin.H {
	return [][]gin.H{entity(g, p, "units", unit)["active_orders"].([]gin.H), g.Risq.PlayerToFrontend(uint64(p+1), g.PlayerID(p))["active_orders"].([]gin.H)}
}

func encoded(t *testing.T, value any) string {
	t.Helper()
	data, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// The generated order is the unit's only order and the player agrees about it
func checkGeneratedOrder(t *testing.T, g *harness.Game, p int, unit, id uint64, typ defs.OrderType, target int64) {
	t.Helper()
	if id == 0 {
		t.Fatal("generated order has no received ID")
	}
	queues := orderQueues(g, p, unit)
	queue := queues[0]
	if len(queue) != 1 || queue[0]["internal_id"] != id || queue[0]["order_type"] != typ || queue[0]["target_id"] != target {
		t.Fatalf("generated unit order mismatch: %v", queue)
	}
	for _, order := range queues[1] {
		if order["internal_id"] == id {
			if encoded(t, order) != encoded(t, queue[0]) {
				t.Fatal("player and unit disagree on generated order")
			}
			return
		}
	}
	t.Fatalf("generated order %d missing from player", id)
}

func checkOrderGone(t *testing.T, g *harness.Game, p int, unit, id uint64) {
	t.Helper()
	for _, queue := range orderQueues(g, p, unit) {
		for _, order := range queue {
			if order["internal_id"] == id {
				t.Fatalf("resolved generated order %d remained active", id)
			}
		}
	}
}

// Units leaving a garrison and orders generated by gather points, each tracked by its own player slot
func TestGatherPointLifecycles(t *testing.T) {
	w := newWorld(t, 11, nil, nil, smallGarrison)
	center := func(slot int) uint64 { return w.buildings(slot)[1] }
	var scenarios []named

	// leaving a garrison hands off to the gather point only when nothing else tells the unit what to do
	for slot, mode := range []string{"gather", "self", "queued-move", "automatic-move", "no-point"} {
		slot, mode := slot, mode
		var unit uint64
		var wood int
		scenarios = append(scenarios, named{"ungarrison " + mode, []step{
			{
				pre: func() {
					w.produce(slot, center(slot), 1, gin.H{"location_kind": 2, "location_id": w.zoneKey(slot, 0, 0), "object_type": 2, "object_id": center(slot)})
				},
				post: func() {
					u := w.fresh(slot, 1)
					if u.GarrisonedIn == nil || *u.GarrisonedIn != center(slot) {
						t.Fatalf("%s: new unit was not garrisoned: %+v", mode, u)
					}
					unit = u.InternalID
				},
			},
			{
				pre: func() {
					if mode == "no-point" {
						w.point(slot, center(slot), gin.H{"clear": true})
					} else if mode != "self" {
						w.point(slot, center(slot), gin.H{"location_kind": 2, "location_id": w.zoneKey(slot, 1, -1), "object_type": 3})
					}
					wood = int(w.g.Self(w.human(slot)).Resources.Wood)
					orders := []defs.OrderFromFrontend{harness.Order(defs.OrderType_UnitUngarrison, []uint64{unit}, 0, false)}
					home := w.home(slot)
					move := harness.OrderMoveZone([]uint64{unit}, home[0], home[1], -1, 1)
					if mode == "queued-move" {
						orders = append(orders, move)
					} else if mode == "automatic-move" {
						orders = []defs.OrderFromFrontend{move}
					}
					w.g.Submit(w.human(slot), orders...)
				},
				post: func() {
					u := unitByID(w.g, w.human(slot), unit)
					gained := int(w.g.Self(w.human(slot)).Resources.Wood) - wood
					switch mode {
					case "gather":
						if gained <= 0 || len(u.ActiveOrders) != 1 || u.ActiveOrders[0].OrderType != uint8(defs.OrderType_UnitGather) {
							t.Fatalf("ungarrisoned unit did not gather: %+v", u)
						}
					case "queued-move", "automatic-move":
						w.expectAt(u, slot, -1, 1)
					default:
						if len(u.ActiveOrders) != 0 || gained != 0 {
							t.Fatalf("%s: ungarrison overrode existing behavior: %+v", mode, u)
						}
					}
					if u.GarrisonedIn != nil {
						t.Fatalf("%s: unit was re-garrisoned", mode)
					}
				},
			},
		}})
	}

	// a generated order is an ordinary received order: it carries, is visible to its player, and can be unsubmitted around, cancelled or replaced
	for i, c := range []struct {
		typ     defs.OrderType
		replace bool
	}{
		{defs.OrderType_UnitMoveSpace, false}, {defs.OrderType_UnitMoveSpace, true},
		{defs.OrderType_UnitMoveZone, false}, {defs.OrderType_UnitMoveZone, true},
		{defs.OrderType_UnitGather, false}, {defs.OrderType_UnitGather, true},
	} {
		slot, typ, replace := 5+i, c.typ, c.replace
		var unit, id uint64
		var target int64
		var before harness.Unit
		var wood int
		point := func() gin.H {
			far := w.farSpace(slot)
			switch typ {
			case defs.OrderType_UnitMoveSpace:
				target = harness.SpaceKey(far[0], far[1])
				return gin.H{"location_kind": 1, "location_id": target}
			case defs.OrderType_UnitMoveZone:
				target = harness.ZoneKey(far[0], far[1], 0, 0)
				return gin.H{"location_kind": 2, "location_id": target}
			}
			target = w.zoneKey(slot, 1, -1)
			return gin.H{"location_kind": 2, "location_id": target, "object_type": 3}
		}
		home := w.home(slot)
		scenarios = append(scenarios, named{fmt.Sprintf("generated %d replace=%v", typ, replace), []step{
			{
				pre: func() { w.produce(slot, center(slot), 1, point()) },
				post: func() {
					u := w.fresh(slot, 1)
					unit, id = u.InternalID, u.ActiveOrders[0].InternalID
					checkGeneratedOrder(t, w.g, w.human(slot), unit, id, typ, target)
				},
			},
			{post: func() { checkGeneratedOrder(t, w.g, w.human(slot), unit, id, typ, target) }},
			{
				pre: func() {
					p := w.human(slot)
					w.g.Submit(p, harness.OrderMoveZone([]uint64{unit}, home[0], home[1], -1, 1))
					if len(w.g.Self(p).ActiveOrders) != 2 {
						t.Fatal("pending order did not coexist with generated order")
					}
					w.g.Action(p, "unsubmit-orders", nil)
					checkGeneratedOrder(t, w.g, p, unit, id, typ, target)
					if len(w.g.Self(p).ActiveOrders) != 1 {
						t.Fatal("unsubmit did not preserve only generated order")
					}
					before, wood = unitByID(w.g, p, unit), int(w.g.Self(p).Resources.Wood)
					order := harness.Order(defs.OrderType_CancelOrder, []uint64{unit}, int64(id), false)
					if replace {
						order = harness.Order(defs.OrderType_UnitMoveZone, []uint64{unit}, harness.ZoneKey(home[0], home[1], -1, 1), true)
					}
					w.g.Submit(p, order)
				},
				post: func() {
					p := w.human(slot)
					checkOrderGone(t, w.g, p, unit, id)
					if int(w.g.Self(p).Resources.Wood) != wood {
						t.Fatal("cancelled or cleared gather order still credited resources")
					}
				},
			},
			{post: func() {
				if replace {
					return
				}
				p := w.human(slot)
				current := unitByID(w.g, p, unit)
				if current.Space != before.Space || current.Zone != before.Zone || len(current.ActiveOrders) != 0 || int(w.g.Self(p).Resources.Wood) != wood {
					t.Fatalf("cancelled generated order resumed: %+v", current)
				}
				checkOrderGone(t, w.g, p, unit, id)
			}},
			{post: func() {
				if !replace {
					return
				}
				p := w.human(slot)
				w.expectAt(unitByID(w.g, p, unit), slot, -1, 1)
				checkOrderGone(t, w.g, p, unit, id)
			}},
		}})
	}

	runScenarios(w, 5, scenarios)
}
